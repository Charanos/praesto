/** Execute with the documented CUA browser API, not a separate browser driver. */
import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { navigate } from './browser-checks.mjs';

export async function reviewOverview(tab, viewport, directory, width) {
  await viewport.set({width,height:1000});
  await tab.playwright.domSnapshot();
  assert.equal(await tab.playwright.evaluate(()=>innerWidth),width);
  await navigate(tab,'Data quality');
  await navigate(tab,'Overview');
  assert.equal(await tab.playwright.locator('.availability-ring-value').textContent(),'59.7%');
  await tab.playwright.locator('.availability-ring .recharts-sector').first().waitFor({state:'visible'});
  assert.equal(await tab.playwright.locator('.availability-ring .recharts-sector').count(),2);
  await tab.playwright.locator('.watch-ledger-select').first().press('Enter');
  await tab.playwright.domSnapshot();
  assert.equal(await tab.playwright.locator('.watch-ledger-row[data-selected="true"]').count(),1);
  assert.ok((await tab.playwright.locator('.watch-ledger-evidence').textContent()).includes('HealthyU'));
  await tab.playwright.locator('.watch-ledger-select').first().press('Enter');
  assert.equal(await tab.playwright.locator('.watch-ledger-row[data-selected="true"]').count(),0);
  await tab.playwright.getByRole('button',{name:'Show more products',exact:true}).press('Enter');
  assert.equal(await tab.playwright.locator('.watch-ledger-row').count(),12);
  await tab.playwright.getByRole('button',{name:'Show fewer products',exact:true}).press('Enter');
  assert.equal(await tab.playwright.locator('.watch-ledger-row').count(),3);
  await tab.playwright.locator('.brief-watch-head .pill-toggle button').nth(1).press('Enter');
  await tab.playwright.domSnapshot();
  assert.equal(await tab.playwright.locator('.watch-ledger-row').count(),3);
  assert.ok((await tab.playwright.locator('#brief-watch-title').textContent()).includes('five or more'));
  await tab.playwright.locator('.brief-watch-head .pill-toggle button').first().press('Enter');
  await tab.playwright.locator('.attention-signal-rows > button').nth(1).press('Enter');
  await tab.playwright.domSnapshot();
  assert.ok((await tab.playwright.locator('.watch-ledger-evidence').textContent()).includes('Rangechem'));
  const focus = await tab.playwright.evaluate(()=>document.activeElement?.id);
  assert.equal(focus,'watchlist-product-title');
  await writeFile(`${directory}/praesto-watchlist-${width}.jpg`,await tab.screenshot({fullPage:false}));
  await tab.playwright.locator('.source-network-tools .pill-toggle button').nth(1).press('Enter');
  assert.equal(await tab.playwright.locator('.source-comparison-name strong').first().textContent(),'Garnet Pharmacy');
  await tab.playwright.locator('.source-network-tools .pill-toggle button').first().press('Enter');
  assert.equal(await tab.playwright.locator('.source-comparison-name strong').first().textContent(),'Tims Nutrition');
  assert.equal(await tab.playwright.locator('.source-comparison-row').count(),8);
  assert.equal(await tab.playwright.locator('.source-listing-links button').count(),7);
  await tab.playwright.getByRole('heading',{name:'An all-category catalogue',exact:true}).click();
  await tab.playwright.domSnapshot();
  await tab.playwright.locator('.catalogue-treemap rect').first().waitFor({state:'visible'});
  assert.equal(await tab.playwright.locator('.catalogue-category-list > button').count(),8);
  assert.equal(await tab.playwright.locator('.catalogue-coverage-list > button').count(),3);
  await tab.playwright.locator('.stockout-groups > summary').press('Enter');
  assert.equal(await tab.playwright.locator('.stockout-group-rows > button').count(),4);
  const groups=await tab.playwright.locator('.stockout-group-count > b').allTextContents({});
  assert.equal(JSON.stringify(groups),JSON.stringify(['2','155','15,453','27,996']));
  await tab.playwright.locator('.price-count-table > summary').press('Enter');
  assert.equal(await tab.playwright.locator('.price-count-table tbody tr').count(),7);
  const priceCounts=await tab.playwright.locator('.price-count-table td').allTextContents({});
  assert.equal(JSON.stringify(priceCounts),JSON.stringify(['2,575','4,203','7,437','14,166','9,625','4,027','1,368']));
  await tab.playwright.locator('.calculation-sensitivity > summary').press('Enter');
  await tab.playwright.locator('.sensitivity-options > button').nth(1).press('Enter');
  assert.ok((await tab.playwright.locator('.sensitivity-note').textContent()).includes('Sensitivity only'));
  assert.equal(await tab.playwright.locator('.sensitivity-rate').nth(1).textContent(),'68.9%');
  assert.equal(await tab.playwright.locator('.availability-ring-value').textContent(),'59.7%');
  await tab.playwright.locator('.sensitivity-options > button').nth(2).press('Enter');
  assert.equal(await tab.playwright.locator('.sensitivity-rate').nth(2).textContent(),'78.5%');
  await tab.playwright.locator('.sensitivity-options > button').first().press('Enter');
  await tab.playwright.locator('.brief-provenance > summary').press('Enter');
  assert.equal(await tab.playwright.locator('.brief-provenance dl > div').count(),7);
  assert.ok((await tab.playwright.locator('.brief-provenance').textContent()).includes('KES 1,730'));
  assert.equal(await tab.playwright.getByRole('link',{name:'By Andishi, opens in a new tab'}).getAttribute('href'),'https://www.andishi.dev/');
  await tab.playwright.getByRole('button',{name:'Run accessibility check',exact:true}).press('Enter');
  await tab.playwright.locator('[data-audit-result]').filter({hasText:'violations'}).waitFor({state:'visible',timeoutMs:20000});
  const axe=JSON.parse(await tab.playwright.locator('[data-audit-result]').textContent());
  assert.equal(axe.violations.length,0);
  const reflow=await tab.playwright.evaluate(()=>({width:innerWidth,overflow:document.documentElement.scrollWidth>innerWidth,headingAlignments:[...document.querySelectorAll('.brief-section')].map(e=>e.getAttribute('data-align')),footer:document.querySelector('.workspace-footer')?.textContent}));
  assert.equal(reflow.overflow,false);
  assert.equal(JSON.stringify(reflow.headingAlignments),JSON.stringify(['right','right','left','right']));
  const result={width,passed:['Recharts ring','single-row evidence expansion','3/12 rows','both queues','sample-to-named-evidence and focus','source ordering','8 reporting/7 listed-only sources','8 categories','coverage groups','stockout groups','exact price table','sensitivity with unchanged headline','provenance','footer'],groups,priceCounts,focus,axe,reflow};
  await writeFile(`${directory}/praesto-overview-workflow-${width}.json`,JSON.stringify(result,null,2));
  for(const selector of ['.price-count-table > summary','.calculation-sensitivity > summary','.stockout-groups > summary','.brief-provenance > summary']) await tab.playwright.locator(selector).press('Enter');
  return result;
}
