import assert from 'node:assert/strict';
import {writeFile} from 'node:fs/promises';
export async function reviewComparison(tab,viewport,directory,width){
 await viewport.set({width,height:900});
 await tab.playwright.domSnapshot();
 const checks=[];
 const list=tab.playwright.getByRole('listbox',{name:'Products to compare'});
 await list.waitFor({state:'visible',timeoutMs:15000});
 assert.equal(await list.getByRole('option').count(),40);
 assert.equal(await tab.playwright.locator('.stock-pattern-nav button').count(),4);
 assert.equal(await tab.playwright.locator('.stock-comparison table').count(),0);
 assert.equal(await tab.playwright.locator('.stock-evidence-sources .pharmacy-glyph').count(),15);
 checks.push('40 sampled products, four patterns, named source partition, no table');
 const first=await tab.playwright.locator('.stock-product-evidence h3').textContent();
 await list.getByRole('option').first().press('ArrowDown');
 await tab.playwright.domSnapshot();
 const second=await tab.playwright.locator('.stock-product-evidence h3').textContent();
 assert.notEqual(first,second);
 assert.equal(await tab.playwright.evaluate(()=>document.activeElement?.getAttribute('aria-selected')),'true');
 checks.push('arrow-key product selection updates named evidence');
 await tab.playwright.getByRole('button',{name:'Out-of-stock reports only 10',exact:true}).click();
 await tab.playwright.domSnapshot();
 assert.equal(await list.getByRole('option').count(),10);
 await tab.playwright.getByRole('button',{name:'Show all patterns',exact:true}).click();
 await tab.playwright.domSnapshot();
 assert.equal(await list.getByRole('option').count(),40);
 const circle=tab.playwright.getByRole('button',{name:'8 products: 2 in-stock sources, 2 out-of-stock sources',exact:true});
 if(width>1100) await circle.press('Enter'); else await circle.click();
 await tab.playwright.locator('.stock-pattern-reset').waitFor({state:'visible'});
 await tab.playwright.getByText('8 shown',{exact:true}).waitFor({state:'visible'});
 await tab.playwright.domSnapshot();
 assert.equal(await list.getByRole('option').count(),8);
 await tab.playwright.getByRole('button',{name:'Show all patterns',exact:true}).click();
 await tab.playwright.domSnapshot();
 checks.push(`pattern selection and ${width>1100?'keyboard':'touch'} circle selection narrow products; reset restores all`);
 await tab.playwright.getByRole('button',{name:'Inspect product',exact:true}).click();
 await tab.playwright.getByRole('dialog').waitFor({state:'visible'});
 const backdrop=await tab.playwright.getByRole('dialog').evaluate(e=>({modal:e.matches(':modal'),background:getComputedStyle(e,'::backdrop').backgroundColor,blur:getComputedStyle(e,'::backdrop').backdropFilter}));
 assert.equal(backdrop.modal,true);assert.equal(backdrop.blur,'blur(3px)');assert.equal(backdrop.background,'rgba(17, 19, 22, 0.42)');
 await tab.playwright.getByRole('dialog').getByRole('button',{name:'Close',exact:true}).press('Escape');
 await tab.playwright.domSnapshot();
 assert.equal(await tab.playwright.getByRole('dialog').count(),0);
 checks.push('product inspector opens as native modal with dimmed blurred background; Escape closes');
 await tab.playwright.getByRole('button',{name:'Run accessibility check',exact:true}).press('Enter');
 await tab.playwright.locator('[data-audit-result]').filter({hasText:'violations'}).waitFor({state:'visible',timeoutMs:20000});
 const audit=JSON.parse(await tab.playwright.locator('[data-audit-result]').textContent());
 assert.equal(audit.violations.length,0,JSON.stringify(audit.violations));
 assert.equal(await tab.playwright.evaluate(()=>document.documentElement.scrollWidth),width);
 checks.push('no horizontal page overflow and zero automated accessibility violations');
 await writeFile(`${directory}/comparison-${width}.png`,await tab.screenshot({fullPage:false}));
 const result={width,checks,backdrop,audit};
 await writeFile(`${directory}/comparison-${width}.json`,JSON.stringify(result,null,2));
 return result;
}
